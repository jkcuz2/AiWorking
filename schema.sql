-- Run this once in Supabase > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.studio_tasks (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text not null,
  created_by text not null,
  assigned_to text not null default 'unassigned',
  claimed_by text,
  status text not null default 'open'
    check (status in ('open', 'in_progress', 'blocked', 'done', 'cancelled')),
  priority text not null default 'normal'
    check (priority in ('low', 'normal', 'high', 'critical')),
  result text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists studio_tasks_status_idx on public.studio_tasks(status, created_at desc);
create index if not exists studio_tasks_assignee_idx on public.studio_tasks(assigned_to, status);

create table if not exists public.studio_messages (
  id bigint generated by default as identity primary key,
  sender text not null,
  recipient text not null default 'all',
  task_id uuid references public.studio_tasks(id) on delete set null,
  body text not null,
  created_at timestamptz not null default now()
);

create index if not exists studio_messages_recipient_idx on public.studio_messages(recipient, id);

-- The app uses the Supabase service-role key on the SERVER only.
-- Enable RLS with no anon/authenticated policies so the tables aren't publicly exposed.
alter table public.studio_tasks enable row level security;
alter table public.studio_messages enable row level security;
